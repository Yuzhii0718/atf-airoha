const struct snand_flash_info *snand_flash_id_lookup(enum snand_id_type type,
						     const uint8_t *id)
{
	const struct snand_id *fid;
	uint32_t i;

	for (i = 0; i < ARRAY_SIZE(snand_flash_ids); i++) {
		if (snand_flash_ids[i].id.type != type)
			continue;

		fid = &snand_flash_ids[i].id;
		if (memcmp(fid->id, id, fid->len))
			continue;

		return &snand_flash_ids[i];
	}

	return NULL;
}

/*
 * Enumeration helpers used by the ecnt flash-table generator and by the
 * runtime table builder.  Keeping the ID array private to this file means the
 * table can stay a verbatim copy of the upstream source.
 */
uint32_t snand_flash_id_count(void)
{
	return ARRAY_SIZE(snand_flash_ids);
}

const struct snand_flash_info *snand_flash_id_index(uint32_t index)
{
	if (index >= ARRAY_SIZE(snand_flash_ids))
		return NULL;

	return &snand_flash_ids[index];
}
